"""
Trading Configuration

Конфигурация параметров торговли.
"""

# ═══════════════════════════════════════════════════════════════════════════
# ПАРАМЕТРЫ УПРАВЛЕНИЯ ПОЗИЦИЯМИ
# ═══════════════════════════════════════════════════════════════════════════

TRADING_CONFIG = {
    # Максимальное количество одновременно открытых позиций на одном счёте
    "max_positions_per_account": 6,
    
    # Минимальный размер позиции в рублях (фильтр слишком маленьких сделок)
    "min_position_size": 0.0,
    
    # Резерв свободной маржи (% от свободной маржи не использовать)
    # Например, 0.1 = оставлять 10% маржи в резерве
    "margin_reserve_percent": 0.0,
}


def get_trading_config() -> dict:
    """
    Получить конфигурацию торговли.
    
    Returns:
        dict: Конфигурация параметров торговли
    """
    return TRADING_CONFIG.copy()


def get_max_positions() -> int:
    """
    Получить максимальное количество позиций на счёте.
    
    Returns:
        int: Максимальное количество позиций
    """
    return TRADING_CONFIG["max_positions_per_account"]
